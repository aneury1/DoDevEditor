#include <chrono>
#include <fstream>
#include <iostream>
#include <stdexcept>

#include "LaunchProfiles.h"
#define CHECK(x)                            \
  do {                                      \
    if (!(x)) throw std::runtime_error(#x); \
  } while (0)
using namespace dodev;
namespace fs = std::filesystem;
struct Temp {
  fs::path root =
      fs::temp_directory_path() /
      ("dodev-launch-profiles-" +
       std::to_string(
           std::chrono::steady_clock::now().time_since_epoch().count()));
  Temp() { fs::create_directories(root / ".vscode"); }
  ~Temp() {
    std::error_code ec;
    fs::remove_all(root, ec);
  }
};
static void put(const fs::path& p, const std::string& v) {
  std::ofstream out(p);
  out << v;
  if (!out) throw std::runtime_error("write failed");
}
template <class F>
void rejects(F f) {
  bool rejected = false;
  try {
    f();
  } catch (const std::exception&) {
    rejected = true;
  }
  CHECK(rejected);
}
int main() {
  try {
    Temp tmp;
    auto p = tmp.root / ".vscode" / "launch.json";
    auto tasks = tmp.root / ".vscode" / "tasks.json";
    put(tasks,
        R"({"version":"2.0.0","tasks":[{"label":"Configure","type":"process","command":"cmake","args":["-S","${workspaceFolder}"]},{"label":"Build","type":"process","command":"cmake","args":["--build","build"],"dependsOn":"Configure","group":{"kind":"build","isDefault":true}}]})");
    put(tmp.root / ".vscode" / "settings.json",
        R"({"app.name":"my app","dodev.taskCommandVariables":{"cmake.launchTargetPath":"build/my app"}})");
    put(p, R"({// JSONC
 "version":"0.2.0","inputs":[{"id":"mode","type":"pickString","description":"Mode","options":["Debug","Release"]}],
 "configurations":[{"name":"Local","type":"cppdbg","request":"launch","program":"${command:cmake.launchTargetPath}","args":["${input:mode}","${input:mode}","${config:app.name}","x; y"],"cwd":"${workspaceFolder}","preLaunchTask":"${defaultBuildTask}","MIMode":"gdb",},
 {"name":"Attach","type":"cppdbg","request":"attach"},],})");
    terminal::TaskContext ctx;
    ctx.workspace = tmp.root;
    int prompts = 0;
    ctx.prompt =
        [&](const terminal::TaskInput& i) -> std::optional<std::string> {
      CHECK(i.id == "mode");
      ++prompts;
      return "Debug";
    };
    auto plan = gdb::planWithoutDebug(ctx, "Local");
    CHECK(plan.size() == 3);
    CHECK(plan[0].label == "Configure");
    CHECK(plan[1].label == "Build");
    CHECK(plan[2].requiredExecutable == tmp.root / "build" / "my app");
    CHECK(plan[2].argv.size() == 5);
    CHECK(plan[2].argv[1] == "Debug" && plan[2].argv[2] == "Debug");
    CHECK(plan[2].argv[3] == "my app" && plan[2].argv[4] == "x; y");
    CHECK(prompts == 1);  // target can be generated by build
    rejects([&] { gdb::planWithoutDebug(ctx, "Attach"); });
    rejects([&] { gdb::planWithoutDebug(ctx, "Removed"); });
    ctx.prompt = [](const auto&) -> std::optional<std::string> {
      return std::nullopt;
    };
    bool cancelled = false;
    try {
      gdb::planWithoutDebug(ctx, "Local");
    } catch (const terminal::TaskCancelled&) {
      cancelled = true;
    }
    CHECK(cancelled);
    auto original = gdb::readJsonc(p);
    auto updated = gdb::appendLaunchProfile(original, "New",
                                            "${workspaceFolder}/build/other");
    CHECK(updated["configurations"].asArray().size() == 3);
    CHECK(updated["inputs"].dump() == original["inputs"].dump());
    CHECK(updated["configurations"].asArray().front().dump() ==
          original["configurations"].asArray().front().dump());
    rejects([&] { gdb::appendLaunchProfile(original, "Local", "x"); });
    put(p, updated.dump());
    rejects([&] { gdb::planWithoutDebug(ctx, "New"); });
    fs::create_directories(tmp.root / "build");
    put(tmp.root / "build" / "other", "test");
    CHECK(gdb::planWithoutDebug(ctx, "New").size() == 1);
#ifndef _WIN32
    put(p,
        R"({"configurations":[{"name":"Env","type":"cppdbg","request":"launch","program":"build/other","environment":[{"name":"MODE","value":"${config:app.name}"}],"args":["one two"]}]})");
    auto env = gdb::planWithoutDebug(ctx, "Env").at(0);
    CHECK(env.argv.at(0) == "env");
    CHECK(env.argv.at(2) == "MODE=my app");
    CHECK(env.argv.at(3) == (tmp.root / "build" / "other").u8string());
    CHECK(env.argv.at(4) == "one two");
#endif
    std::cout << "launch profile creation, selection, dependencies, variables, "
                 "cancellation and missing executable OK\n";
    return 0;
  } catch (const std::exception& e) {
    std::cerr << e.what() << '\n';
    return 1;
  }
}
